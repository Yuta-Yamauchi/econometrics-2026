# Run from the repository root: Rscript --vanilla scripts/lecture07/prepare-data.R
# Base R only. The CSV files contain the first examples from the lecture slides.
args <- commandArgs(trailingOnly = FALSE)
script <- normalizePath(sub("^--file=", "", args[grepl("^--file=", args)]), winslash = "/")
script_dir <- dirname(script)
root <- normalizePath(file.path(script_dir, "../.."), winslash = "/")
mean_y <- read.csv(file.path(script_dir, "mean_sample.csv"))$y
reg <- read.csv(file.path(script_dir, "regression_sample.csv"))
levels <- c(90, 95, 99)
dfs <- sort(unique(c(4, 24, 99, 399, 8, 23, 98, 398)))
number <- function(x) sprintf("%.17g", x)
array_js <- function(x) paste0("[", paste(number(x), collapse = ","), "]")
named_js <- function(names, values) paste0("{", paste(sprintf('"%s":%s', names, number(values)), collapse = ","), "}")
z <- qnorm((1 + levels / 100) / 2)
t_js <- paste0("{", paste(vapply(dfs, function(df) paste0('"', df, '":', named_js(levels, qt((1 + levels / 100) / 2, df))), character(1)), collapse = ","), "}")
fit <- lm(y ~ x, data = reg)
mean_expected <- c(mean = mean(mean_y), sd = sd(mean_y), se = sd(mean_y) / sqrt(length(mean_y)))
reg_expected <- c(intercept = coef(fit)[1], slope = coef(fit)[2], sd = sigma(fit), se = coef(summary(fit))[2, 2], sxx = sum((reg$x - mean(reg$x))^2))
names(reg_expected) <- c("intercept", "slope", "sd", "se", "sxx")
js <- paste0("// Generated by scripts/lecture07/prepare-data.R; do not edit the quantiles by hand.\n",
  "(function(root){'use strict'; const data={\n",
  '"z":', named_js(levels, z), ',\n"t":', t_js,
  ',\n"meanY":', array_js(mean_y), ',\n"regressionX":', array_js(reg$x), ',\n"regressionY":', array_js(reg$y),
  ',\n"expectedMean":', named_js(names(mean_expected), mean_expected),
  ',\n"expectedRegression":', named_js(names(reg_expected), reg_expected),
  "\n};root.CIReference=data;if(typeof module!=='undefined')module.exports=data;\n})(typeof globalThis!=='undefined'?globalThis:this);\n")
writeLines(js, file.path(root, "docs/lecture07/assets/js/reference-data.js"), useBytes = TRUE)
cat("Reference data written; mean n =", length(mean_y), "; regression n =", nrow(reg), "\n")
